// قراءة البيانات المحفوظة
function getData(key, fallback) {
    try {
        return JSON.parse(localStorage.getItem(key)) || fallback;
    } catch {
        return fallback;
    }
}

// حفظ بيانات الطالب والانتقال التلقائي للغلاف
function saveStudent(event) {
    event.preventDefault();

    let name = document.getElementById("studentName").value.trim();
    let grade = document.getElementById("studentGrade").value.trim();

    if (!name || !grade) return;

    localStorage.setItem("studentInfo", JSON.stringify({
        name: name,
        grade: grade
    }));

    document.getElementById("studentMessage").textContent = "تم حفظ بياناتك بنجاح! جاري الانتقال لصفحة الغلاف...";

    setTimeout(() => {
        showPage('cover');
    }, 1000);

    updateDashboard();
}

document.getElementById("studentForm").addEventListener("submit", saveStudent);

// الانتقال بين صفحات الموقع
function showPage(pageId) {
    document.querySelectorAll(".page").forEach(page => {
        page.classList.remove("active");
    });

    document.getElementById(pageId).classList.add("active");

    if (pageId === "home") updateDashboard();
    if (pageId === "certificate") showCertificate();

    window.scrollTo(0, 0);
}

