// بناء الاختبار التفاعلي للدرس
function startQuiz() {
    let lesson = lessons[currentLesson];

    document.getElementById("quizTitle").textContent = "اختبار الدرس: " + lesson.title;

    let html = "";

    lesson.questions.forEach((q, i) => {
        html += `
            <div class="question">
                <strong>${i + 1}. ${q[0]}</strong>
        `;

        q[1].forEach((answer, j) => {
            html += `
                <label>
                    <input type="radio" name="q${i}" value="${j}">
                    ${answer}
                </label>
            `;
        });

        html += `</div>`;
    });

    document.getElementById("quizForm").innerHTML = html;
    document.getElementById("quizResult").innerHTML = "";

    showPage("quizPage");
}

// تصحيح الاختبار وحفظ الدرجات والتقدم
function gradeQuiz() {
    let questions = lessons[currentLesson].questions;
    let score = 0;
    let unanswered = 0;
    let details = "";

    questions.forEach((q, i) => {
        let selected = document.querySelector(`input[name="q${i}"]:checked`);

        if (!selected) {
            unanswered++;
            details += `<p>السؤال ${i + 1}: لم تتم الإجابة عنه.</p>`;
            return;
        }

        let answer = Number(selected.value);

        if (answer === q[2]) {
            score++;
            details += `<p class="correct" style="color: #18835d; font-weight: bold;">السؤال ${i + 1}: إجابة صحيحة ✓</p>`;
        } else {
            details += `
                <p class="incorrect" style="color: #c53030;">
                    السؤال ${i + 1}: إجابة غير صحيحة ✗
                    <br><span style="color: #26364a;">الإجابة الصحيحة: ${q[1][q[2]]}</span>
                </p>
            `;
        }
    });

    if (unanswered > 0) {
        document.getElementById("quizResult").innerHTML =
            `<p style="color: #c53030; font-weight: bold;">الرجاء الإجابة عن جميع الأسئلة أولًا. الأسئلة المتبقية: ${unanswered}</p>`;
        return;
    }

    let results = getData("quizResults", {});
    let previous = results[currentLesson];

    if (!previous || score > previous.score) {
        results[currentLesson] = {
            score: score,
            date: new Date().toLocaleDateString("ar-EG")
        };
    }

    localStorage.setItem("quizResults", JSON.stringify(results));

    let completed = getData("completedLessons", []);

    if (!completed.includes(currentLesson)) {
        completed.push(currentLesson);
    }

    localStorage.setItem("completedLessons", JSON.stringify(completed));

    let message = score >= 8
        ? "ممتاز! أداء رائع وفهم عميق للمحتوى."
        : score >= 5
        ? "جيد جدًا، ننصح بمراجعة بعض أجزاء الدرس."
        : "حاول مراجعة محتوى الدرس مرة أخرى لتحسين مستواك.";

    document.getElementById("quizForm").innerHTML = "";

    document.getElementById("quizResult").innerHTML = `
        <div class="result-box">
            <h2>نتيجة اختبار الدرس</h2>
            <h1>${score} / 10</h1>
            <p>${message}</p>
            <p>تم تسجيل إتمام الدرس بنجاح.</p>
        </div>

        <h3 style="margin-top: 20px;">مراجعة الإجابات والتفاصيل:</h3>
        ${details}

        <button class="primary" onclick="openLesson(${currentLesson})" style="margin-top: 15px;">
            مراجعة الدرس مرة أخرى
        </button>

        <button class="secondary" onclick="showPage('home')">
            العودة للرئيسية والدروس
        </button>
    `;

    updateDashboard();
}

